const existingById = new Map(existingCards.map((c) => [c.id, c]));
const existingByEnType = new Map(
  existingCards.map((c) => [`${c.type}:${c.en.trim().toLowerCase()}`, c])
);

let addedCount = 0;
let updatedUnitCount = 0;

for (const item of THEMATIC_ADDITIONS) {
  const key = `${item.type}:${item.en.trim().toLowerCase()}`;
  const found = existingById.get(item.id) || existingByEnType.get(key);
  if (found) {
    found.unitId = item.unitId;
    for (const tr of item.acceptedTr) {
      if (!found.acceptedTr.some((x) => x.toLowerCase() === tr.toLowerCase())) {
        found.acceptedTr.unshift(tr);
      }
    }
    if (item.exampleEn && (!found.exampleEn || found.exampleEn.length < 15)) {
      found.exampleEn = item.exampleEn;
      found.exampleTr = item.exampleTr;
    }
    updatedUnitCount += 1;
  } else {
    const newCard = {
      ...item,
      source: 'builtin',
    };
    existingCards.push(newCard);
    existingById.set(newCard.id, newCard);
    existingByEnType.set(key, newCard);
    addedCount += 1;
  }
}

fs.writeFileSync(CARDS_PATH, JSON.stringify(existingCards, null, 2), 'utf8');
console.log(
  `[enrich_curriculum_cards] Added ${addedCount} new thematic cards, tagged ${updatedUnitCount} existing cards. Total deck size: ${existingCards.length}`
);
